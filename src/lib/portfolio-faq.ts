/** 어느 사례에나 붙는 마무리 질문 — 답변은 카테고리명을 넣어 페이지마다 달라진다 */
function closingEntry(item: PortfolioItem): FaqEntry {
  const kind = item.category || "종이 구조물";
  return {
    question: "이 사례와 비슷하게 제작하려면 어떻게 문의하나요?",
    answer: `제작 문의 페이지에서 수량·용도·희망 일정을 남겨 주시면 3영업일 이내에 담당자가 회신드립니다. ${kind} 제작은 상담·기획, 구조 설계와 샘플링, 디자인, 생산·납품 순으로 진행되며 평균 3~4주가 걸립니다. 페이퍼토이 기준 최소 수량은 1,000부입니다.`,
  };
}

/**
 * 사례 하나에 붙일 FAQ 목록. 카테고리·클라이언트 유형이 비어 있거나 등록되지 않은
 * 값이면 해당 항목을 건너뛴다 — 억지로 채우면 엉뚱한 답이 나간다.
 */
export function derivePortfolioFaq(item: PortfolioItem): FaqEntry[] {
  const entries: FaqEntry[] = [];

  const byCat = item.category ? BY_CATEGORY[item.category] : undefined;
  if (byCat) entries.push(byCat);

  const byType = item.clientType ? BY_CLIENT_TYPE[item.clientType] : undefined;
  if (byType) entries.push(byType);

  entries.push(closingEntry(item));
  return entries;
}
